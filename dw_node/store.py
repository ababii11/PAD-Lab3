"""Everything that touches this node's own MongoDB.

Document layout in the `movies` collection:
    _id         movie id (UUID string, generated by the node that creates it)
    title, year, genre, actors, rating   -- the business data
    version     integer, +1 on every change, wherever the change happens
    node        name of the node that made this version (tie-breaker)
    updated_at  ISO time, for display only -- NEVER used to decide conflicts
    deleted     True for a tombstone (soft delete)

Conflict rule, identical on every node:
    version A beats version B  <=>  (A.version, A.node) > (B.version, B.node)

Other collections:
    changes   {seq, ts, doc}  -- change log of LOCAL writes only (the change feed)
    counters  {_id: "changes", n}  -- last used sequence number
    peers     {_id: peer name, last_seq, instance, url}  -- how far we pulled
    meta      {_id: "instance", value}  -- random id of this database
"""
import asyncio
import hashlib
import logging
import uuid
from datetime import datetime, timedelta, timezone

from pymongo import ASCENDING, AsyncMongoClient, ReturnDocument
from pymongo.errors import DuplicateKeyError, OperationFailure
from pymongo.uri_parser import parse_uri

from . import settings

log = logging.getLogger("dw.store")

BUSINESS_FIELDS = ("title", "year", "genre", "actors", "rating")


class NotFound(Exception):
    pass


class VersionConflict(Exception):
    def __init__(self, current_version: int):
        super().__init__(current_version)
        self.current_version = current_version


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


def is_newer(a: dict, b: dict) -> bool:
    """True if version `a` beats version `b` (same rule on every node)."""
    return (a["version"], a["node"]) > (b["version"], b["node"])


def public(doc: dict) -> dict:
    """Shape a stored document for API output."""
    out = {"id": doc["_id"]}
    for field in BUSINESS_FIELDS:
        if field in doc:
            out[field] = doc[field]
    out["version"] = doc["version"]
    out["node"] = doc["node"]
    out["updated_at"] = doc.get("updated_at")
    return out


class Store:
    def __init__(self) -> None:
        self.client: AsyncMongoClient | None = None
        self.db = None
        self.instance: str = ""

    @staticmethod
    def _new_client() -> AsyncMongoClient:
        return AsyncMongoClient(settings.MONGO_URL, serverSelectionTimeoutMS=3000, tz_aware=True)

    # ---------- startup ----------
    async def init(self) -> None:
        # Check / initiate the replica set with a temporary client, then open the
        # real one: a client that first saw an uninitiated server would keep
        # treating it as a standalone server (no sessions, no transactions).
        probe = self._new_client()
        try:
            await self._ensure_replica_set(probe)
        finally:
            await probe.close()
        self.client = self._new_client()
        self.db = self.client[settings.MONGO_DB]
        await self.db.changes.create_index([("seq", ASCENDING)], unique=True)
        await self.db.changes.create_index([("ts", ASCENDING)])
        await self.db.movies.create_index([("deleted", ASCENDING), ("updated_at", ASCENDING)])
        meta = await self.db.meta.find_one({"_id": "instance"})
        if meta is None:
            try:
                await self.db.meta.insert_one({"_id": "instance", "value": uuid.uuid4().hex})
            except DuplicateKeyError:
                pass
            meta = await self.db.meta.find_one({"_id": "instance"})
        self.instance = meta["value"]
        log.info("database ready (instance %s)", self.instance)

    @staticmethod
    async def _ensure_replica_set(client: AsyncMongoClient) -> None:
        """Turn a fresh `mongod --replSet ...` into a working one-member replica set."""
        admin = client.admin
        for _ in range(60):
            try:
                hello = await admin.command("hello")
                if hello.get("isWritablePrimary"):
                    return
                if "setName" not in hello:
                    opts = await admin.command("getCmdLineOpts")
                    repl = opts["parsed"].get("replication", {})
                    rs_name = repl.get("replSetName") or repl.get("replSet")
                    if not rs_name:
                        raise RuntimeError(
                            "mongod must be started with --replSet <name> "
                            "(transactions need replica-set mode)")
                    host, port = parse_uri(settings.MONGO_URL)["nodelist"][0]
                    cfg = {"_id": rs_name, "members": [{"_id": 0, "host": f"{host}:{port}"}]}
                    try:
                        await admin.command("replSetInitiate", cfg)
                        log.info("initiated replica set %s", rs_name)
                    except OperationFailure as exc:
                        if exc.code != 23:  # 23 = AlreadyInitialized
                            raise
            except OperationFailure as exc:
                if exc.code != 94:  # 94 = NotYetInitialized
                    raise
            except RuntimeError:
                raise
            except Exception as exc:  # mongod not reachable yet
                log.info("waiting for MongoDB: %s", exc)
            await asyncio.sleep(1)
        raise RuntimeError("MongoDB did not become a writable primary")

    async def ping(self) -> bool:
        try:
            await asyncio.wait_for(self.client.admin.command("ping"), timeout=2)
            return True
        except Exception:
            return False

    # ---------- reads ----------
    async def list_movies(self, offset: int, limit: int) -> tuple[int, list[dict]]:
        query = {"deleted": False}
        total = await self.db.movies.count_documents(query)
        cursor = (self.db.movies.find(query).sort([("title", ASCENDING), ("_id", ASCENDING)])
                  .skip(offset).limit(limit))
        return total, [public(d) async for d in cursor]

    async def get_movie(self, movie_id: str) -> dict:
        doc = await self.db.movies.find_one({"_id": movie_id, "deleted": False})
        if doc is None:
            raise NotFound()
        return public(doc)

    # ---------- local writes (create / update / delete) ----------
    async def local_write(self, movie_id: str, fields: dict | None, *,
                          expected_version: int | None, must_exist: bool) -> dict:
        """Write a movie and its change-log entry in ONE transaction.

        fields=None means delete (store a tombstone).
        expected_version enables optimistic concurrency (HTTP If-Match).
        """
        result: dict = {}

        async def txn(session):
            current = await self.db.movies.find_one({"_id": movie_id}, session=session)
            live = current is not None and not current.get("deleted")
            if must_exist and not live:
                raise NotFound()
            if expected_version is not None and live and current["version"] != expected_version:
                raise VersionConflict(current["version"])

            new_doc = {
                "_id": movie_id,
                "version": (current["version"] if current else 0) + 1,
                "node": settings.NODE_NAME,
                "updated_at": now_iso(),
                "deleted": fields is None,
            }
            if fields is not None:
                new_doc.update(fields)
            await self.db.movies.replace_one({"_id": movie_id}, new_doc, upsert=True,
                                             session=session)
            # Sequence number taken inside the same transaction: two concurrent
            # writes on this node can never commit with out-of-order numbers.
            counter = await self.db.counters.find_one_and_update(
                {"_id": "changes"}, {"$inc": {"n": 1}}, upsert=True,
                return_document=ReturnDocument.AFTER, session=session)
            await self.db.changes.insert_one(
                {"seq": counter["n"], "ts": datetime.now(timezone.utc), "doc": new_doc},
                session=session)
            result.clear()
            result.update(new_doc)

        async with self.client.start_session() as session:
            await session.with_transaction(txn)  # retries on transient write conflicts
        return result

    # ---------- applying changes that came from other nodes ----------
    async def apply_remote(self, doc: dict) -> bool:
        """Store `doc` only if it is newer than our copy. Safe to repeat.

        Remote changes are NOT written to our change log: every node pulls from
        every other node directly, so re-logging would only echo changes back.
        """
        newer_than_ours = {
            "_id": doc["_id"],
            "$or": [
                {"version": {"$lt": doc["version"]}},
                {"version": doc["version"], "node": {"$lt": doc["node"]}},
            ],
        }
        try:
            res = await self.db.movies.replace_one(newer_than_ours, doc, upsert=True)
            return bool(res.modified_count or res.upserted_id)
        except DuplicateKeyError:
            return False  # we already hold the same or a newer version

    # ---------- change feed ----------
    async def changes_since(self, since: int, limit: int) -> dict:
        counter = await self.db.counters.find_one({"_id": "changes"})
        max_seq = counter["n"] if counter else 0
        first = await self.db.changes.find_one({}, sort=[("seq", ASCENDING)])
        min_seq = first["seq"] if first else max_seq + 1
        cursor = self.db.changes.find({"seq": {"$gt": since}}).sort("seq", ASCENDING).limit(limit)
        items = [{"seq": c["seq"], "doc": c["doc"]} async for c in cursor]
        return {"node": settings.NODE_NAME, "instance": self.instance,
                "min_seq": min_seq, "max_seq": max_seq, "changes": items}

    # ---------- reconciliation ----------
    async def digest(self) -> list[list]:
        cursor = self.db.movies.find({}, {"version": 1, "node": 1})
        return [[d["_id"], d["version"], d["node"]] async for d in cursor]

    async def docs_by_ids(self, ids: list[str]) -> list[dict]:
        return [d async for d in self.db.movies.find({"_id": {"$in": ids}})]

    async def checksum(self) -> dict:
        h = hashlib.sha256()
        total = live = 0
        async for d in self.db.movies.find({}, {"version": 1, "node": 1, "deleted": 1}).sort("_id", 1):
            total += 1
            live += 0 if d.get("deleted") else 1
            h.update(f"{d['_id']}:{d['version']}:{d['node']}:{int(bool(d.get('deleted')))}\n".encode())
        return {"node": settings.NODE_NAME, "live": live, "total": total,
                "hash": h.hexdigest()[:16]}

    # ---------- peer bookkeeping ----------
    async def get_peer(self, name: str) -> dict | None:
        return await self.db.peers.find_one({"_id": name})

    async def save_peer(self, name: str, **fields) -> None:
        await self.db.peers.update_one({"_id": name}, {"$set": fields}, upsert=True)

    async def peers(self) -> list[dict]:
        return [p async for p in self.db.peers.find({})]

    # ---------- housekeeping ----------
    async def trim(self) -> None:
        now = datetime.now(timezone.utc)
        cut_changes = now - timedelta(hours=settings.CHANGE_RETENTION_HOURS)
        res = await self.db.changes.delete_many({"ts": {"$lt": cut_changes}})
        cut_tomb = (now - timedelta(hours=settings.TOMBSTONE_RETENTION_HOURS)).isoformat()
        res2 = await self.db.movies.delete_many({"deleted": True, "updated_at": {"$lt": cut_tomb}})
        if res.deleted_count or res2.deleted_count:
            log.info("trimmed %d change-log entries, %d old tombstones",
                     res.deleted_count, res2.deleted_count)
